import { test, expect, type Page } from "@playwright/test"

const fixture = (page: Page) => page.evaluate(() => window.__automationAcceptance.snapshot())
const section = (page: Page) => page.getByTestId("personal-jobs-control")
const taskPanel = (page: Page) => page.locator("#operations-task-editor")
const job = (page: Page, title: string) => section(page).getByTestId("personal-job-card").filter({ has: page.getByText(title, { exact: true }) })
const task = (page: Page, title: string) => taskPanel(page).locator("article").filter({ has: page.getByText(title, { exact: true }) })
const calls = async (page: Page, name: string) => (await fixture(page)).calls.filter(c => c.action === name)
async function open(page: Page, tasks = false) {
  await page.goto(tasks ? "/?panel=tasks" : "/")
  await expect(page.getByTestId("session-operations")).toHaveAttribute("aria-busy", "false")
  if (!tasks) await expect(section(page)).toHaveAttribute("aria-busy", "false")
}
async function confirm(page: Page, activate: () => Promise<unknown>, accepted = true) {
  await activate()
  const modal = page.getByRole("dialog", { name: "Confirm action", exact: true })
  await expect(modal).toBeVisible()
  await modal.getByRole("button", { name: accepted ? "Confirm" : "Cancel", exact: true }).click()
}
test.afterEach(async ({ page }, info) => {
  if (!page.isClosed()) {
    await info.attach("actual-production-ui", { body: await page.locator("body").innerText(), contentType: "text/plain" })
    await info.attach("stateful-isolated-protocol", { body: JSON.stringify(await fixture(page)), contentType: "application/json" })
    await expect.poll(async () => (await fixture(page)).violations).toEqual([])
  }
})

test("[goals-s01] empty Task list preserves separate Goal and Task editors", async ({ page }) => {
  await open(page, true)
  await page.evaluate(() => window.__automationAcceptance.scenario("empty-tasks"))
  await page.locator(".session-settings-context-actions button").click()
  await expect(taskPanel(page).locator("article")).toHaveCount(0)
  await expect(taskPanel(page).getByLabel("Task title", { exact: true })).toBeEmpty()
  await expect(taskPanel(page).getByRole("button", { name: "Create Task", exact: true })).toBeDisabled()
  await expect(page.getByRole("button", { name: "Create Goal", exact: true })).toBeVisible()
})
test("[goals-s03] blocked Task cannot be claimed; owner claim/release and completion unlock dependencies", async ({ page }) => {
  await open(page, true)
  await expect(task(page, "Blocked task")).toContainText("1 unresolved blocker")
  await expect(task(page, "Blocked task").getByRole("button", { name: "Claim", exact: true })).toBeDisabled()
  await taskPanel(page).getByLabel("Claim owner", { exact: true }).fill("worker-acceptance")
  await task(page, "Root task").getByRole("button", { name: "Claim", exact: true }).click()
  await expect(task(page, "Root task")).toContainText("owner worker-acceptance")
  expect((await calls(page, "task:claim"))[0]?.body).toEqual({ expectedRevision: 1, owner: "worker-acceptance" })
  await task(page, "Root task").getByRole("button", { name: "Release", exact: true }).click()
  await expect(task(page, "Root task").getByRole("button", { name: "Claim", exact: true })).toBeEnabled()
  await task(page, "Root task").getByRole("button", { name: "Complete", exact: true }).click()
  await expect(task(page, "Root task")).toContainText("Completed")
  await expect(task(page, "Blocked task").getByRole("button", { name: "Claim", exact: true })).toBeEnabled()
})
