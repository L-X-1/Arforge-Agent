test("[jobs-s03 jobs-s04] pause and held resume retain truthful status and disable duplicate writes", async ({ page }) => {
  await open(page)
  const running = job(page, "Fixture running")
  await running.getByRole("button", { name: "Pause", exact: true }).click()
  await expect(running).toContainText("Paused")
  await page.evaluate(() => window.__automationAcceptance.hold("job:resume"))
  await running.getByRole("button", { name: "Resume", exact: true }).click()
  await expect(section(page)).toHaveAttribute("aria-busy", "true")
  await expect(running).toContainText("Paused")
  await expect(running.getByRole("button", { name: "Resume", exact: true })).toBeDisabled()
  await page.evaluate(() => window.__automationAcceptance.release("job:resume"))
  await expect(running).toContainText("Queued")
  expect(await calls(page, "job:resume")).toHaveLength(1)
})
