const test = base.extend<{ fence: void }>({ fence: [async ({ context }, use) => {
  const blocked: string[] = [], errors: string[] = []
  await context.route("**/*", async route => {
    const request = route.request(), url = new URL(request.url())
    if (url.origin !== "http://127.0.0.1:4479" || !["GET", "HEAD"].includes(request.method())) { blocked.push(request.method() + " " + url.origin + url.pathname); return route.abort() }
    return route.continue()
  })
  await context.routeWebSocket(/.*/, socket => { socket.close() })
  context.on("page", page => page.on("pageerror", error => errors.push(error.stack ?? error.message)))
  await use(); expect(blocked).toEqual([]); expect(errors).toEqual([])
}, { auto: true }] })
