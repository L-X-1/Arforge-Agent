  await page.getByRole("button", { name: "Open isolated approvals", exact: true }).click()
  const dialog = page.getByTestId("control-approval-dialog"), card = dialog.getByTestId("control-approval-card")
  await card.getByRole("button", { name: "Approve this time", exact: true }).click()
  await expect.poll(async () => page.evaluate(() => window.__approvalAcceptance.snapshot().calls.length)).toBe(1)
  await page.evaluate(() => window.__approvalAcceptance.settleReply("source-a", 0, "confirmed"))
  const receipt = dialog.getByTestId("control-approval-receipt")
  await expect(receipt).toHaveAttribute("data-state", "confirmed")
  expect(await page.evaluate(() => window.__approvalAudit.snapshot().reads)).toEqual([])
  await expect(receipt.locator("[data-execution-phase]")).toHaveCount(0)
  await page.evaluate(() => window.__approvalAudit.failStatus(true))
