import { test, expect } from '@playwright/test'
const root=(page:any)=>page.getByTestId('runtime-insight-workbench')
test.beforeEach(async({page})=>{await page.route('**/*',r=>new URL(r.request().url()).origin==='http://127.0.0.1:4631'?r.continue():r.abort())})
test.afterEach(async({page},info)=>{
 console.log('runtime UI assertions finished; collecting evidence',info.title)
 await info.attach('actual-runtime-ui',{body:await page.locator('body').innerText(),contentType:'text/plain'})
 await info.attach('fixture-actions',{body:JSON.stringify(await page.evaluate(()=>({locations:window.runtimeInsightFixture.locationCalls,reads:window.runtimeInsightFixture.recoveryCalls,reviews:window.runtimeInsightFixture.reviews,verifications:window.runtimeInsightFixture.verificationCalls}))),contentType:'application/json'})
 console.log('runtime evidence attached')
})
test('[runtime-s01] initial snapshot loading disables refresh and becomes readable only after response',async({page})=>{
 await page.goto('/?scenario=loading')
 await expect(root(page)).toHaveAttribute('aria-busy','true')
 await expect(root(page).getByRole('button',{name:/Refreshing/}).first()).toBeDisabled()
 await page.evaluate(()=>window.runtimeInsightFixture.resolveSnapshot())
 await expect(root(page)).toHaveAttribute('aria-busy','false')
 await root(page).getByRole('tab',{name:'Durable runs and crash recovery',exact:true}).click()
 await expect(page.getByTestId('durable-runtime-card')).toBeVisible()
})
test('[runtime-s02 runtime-s04] empty snapshot has honest empty state and no invented successful verification',async({page})=>{
 await page.goto('/?scenario=empty')
 await expect(root(page)).toHaveAttribute('aria-busy','false')
 await expect(page.getByTestId('runtime-insight-empty-state')).toBeVisible()
 await root(page).getByRole('tab',{name:'Pre-delivery verification',exact:true}).click()
 const verification=root(page).getByRole('tabpanel',{name:'Pre-delivery verification',exact:true})
 await expect(verification).toContainText('No records yet.')
 await expect(verification.locator('button[data-management-detail-id]')).toHaveCount(0)
 await expect(root(page)).not.toContainText('Verification passed')
 expect(await page.evaluate(()=>window.runtimeInsightFixture.verificationCalls)).toBe(0)
})
test('[runtime-s03] source snapshot displays model, source path and exact token amount without execution',async({page})=>{
 await page.goto('/?scenario=sources')
 await root(page).getByRole('tab',{name:'Model context composition',exact:true}).click()
 await root(page).getByRole('tabpanel',{name:'Model context composition',exact:true}).locator('button[data-management-detail-id]').filter({hasText:'fixture-provider/fixture-model'}).click()
 await expect(root(page)).toContainText('C:/Isolated/Lifecycle/ARFORGE.md')
 await expect(root(page)).toContainText('fixture-provider/fixture-model')
 await expect(root(page)).toContainText('22 tok')
 expect(await page.evaluate(()=>window.runtimeInsightFixture.reviews)).toEqual([])
})
test('[runtime-s05] invalid audit snapshot and explicit recheck cannot report a valid chain',async({page})=>{
 await page.goto('/?scenario=audit-invalid')
 await expect(root(page)).toHaveAttribute('aria-busy','false')
 await expect(root(page)).toContainText('Invalid')
 await root(page).getByRole('tab',{name:'Operation audit',exact:true}).click()
 await root(page).getByRole('button',{name:'More actions',exact:true}).click()
 await page.getByRole('menuitem',{name:/^Verify (?:tamper protection|audit chain)$/}).click()
 await expect.poll(()=>page.evaluate(()=>window.runtimeInsightFixture.verificationCalls)).toBe(1)
 await expect(root(page)).toContainText('Isolated missing audit segment')
 await expect(root(page)).not.toContainText('Valid chain')
 await expect(root(page).getByRole('tabpanel',{name:'Operation audit',exact:true})).not.toContainText('Intact')
})
test('[runtime-s06] failed recovery read cannot mutate; retry inspects current target and source switch clears details',async({page})=>{
 await page.setViewportSize({width:375,height:1000});await page.emulateMedia({colorScheme:'dark'})
 await page.goto('/')
 await root(page).getByRole('tab',{name:'Real actions and impact',exact:true}).click()
 await root(page).getByRole('tabpanel',{name:'Real actions and impact',exact:true}).locator('button[data-management-detail-id]').filter({hasText:'act_runtime_insight_fixture'}).click()
 const action=page.locator('[data-testid="durable-action-record"][data-action-id="act_runtime_insight_fixture"]')
 await page.evaluate(()=>{window.runtimeInsightFixture.recoveryFailure=true})
 await action.getByRole('button',{name:'Inspect current target state: write',exact:true}).click()
 await expect(root(page)).toContainText('Isolated recovery read failed')
 expect(await page.evaluate(()=>window.runtimeInsightFixture.recoveryCalls)).toEqual(['act_runtime_insight_fixture'])
 expect(await page.evaluate(()=>window.runtimeInsightFixture.reviews)).toEqual([])
 await page.evaluate(()=>{window.runtimeInsightFixture.recoveryFailure=false})
 await action.getByRole('button',{name:'Inspect current target state: write',exact:true}).click()
 await expect(action.getByTestId('durable-action-inspection')).toBeVisible()
 await page.evaluate(()=>window.runtimeInsightFixture.setWorkspace('workspace-two'))
 await expect(action.getByTestId('durable-action-inspection')).toHaveCount(0)
 await expect(root(page)).toHaveAttribute('aria-busy','false')
 await page.screenshot({path:test.info().outputPath('runtime-375-dark.png'),fullPage:true})
})
