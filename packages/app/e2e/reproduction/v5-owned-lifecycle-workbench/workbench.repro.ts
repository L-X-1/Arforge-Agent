import { expect, test, type Page } from '@playwright/test'
const fixture = async (page: Page) => JSON.parse(await page.evaluate(() => JSON.stringify((window as any).__lifecycleWorkbench.snapshot())))
const governance = (page: Page) => page.getByTestId('memory-governance')
const memory = (page: Page) => page.getByTestId('memory-persisted')
const candidate = (page: Page, status: string) => page.locator('section').filter({ has: page.getByRole('heading', { name: 'Fixture strategy '+status, exact: true }) }).last()
async function selectCandidate(page: Page, title: string) {
 await page.getByTestId('evolution-workbench').locator('button[data-management-detail-id]').filter({hasText:title}).click()
}
async function confirm(page: Page, accepted=true) {
 const dialog=page.getByRole('dialog',{name:'Confirm action',exact:true});await expect(dialog).toBeVisible()
 await dialog.getByRole('button',{name:accepted?'Confirm':'Cancel',exact:true}).click()
}
