test.afterEach(async({page},info)=>{
 console.log('workbench UI assertions finished; collecting evidence', info.title)
 await info.attach('actual-production-ui',{body:await page.locator('body').innerText(),contentType:'text/plain'})
 console.log('workbench DOM attached; collecting protocol')
 await info.attach('stateful-isolated-api',{body:JSON.stringify(await fixture(page)),contentType:'application/json'})
 console.log('workbench protocol attached')
})
async function open(page: Page, evolution=false) {
 await page.goto(evolution?'/?page=evolution':'/')
 await expect(evolution?page.getByTestId('evolution-workbench'):memory(page).getByTestId('control-center-memory')).toHaveAttribute('aria-busy','false')
}
