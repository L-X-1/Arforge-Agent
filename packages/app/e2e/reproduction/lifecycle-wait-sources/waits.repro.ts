import { test,expect } from "@playwright/test"
test.beforeEach(async({page})=>{await page.route("**/*",route=>new URL(route.request().url()).origin==="http://127.0.0.1:4637"?route.continue():route.abort());await page.goto("/");await expect(page.getByTestId("wait-approval-source")).toBeVisible()})
test.afterEach(async({page})=>{expect(await page.evaluate(()=>window.__waitSources.violations)).toEqual([])})
test("approval exact source, foreground child, missing receipt and completion use only reads",async({page})=>{
  const panel=page.getByTestId("session-wait-sources")
  await expect(panel.getByTestId("wait-approval-source")).toContainText("per_a")
  await expect(panel.getByTestId("wait-approval-source")).toContainText("run_a")
  await page.screenshot({path:test.info().outputPath("approval-source.png"),fullPage:true})
  expect(await panel.getByRole("button").allTextContents()).toEqual(["Refresh sources"])
  await page.evaluate(()=>window.__waitSources.scenario("child"));await panel.getByRole("button").click()
  await expect(panel.getByTestId("wait-child-source")).toContainText("run_child_a")
  await expect(panel.getByTestId("wait-child-source")).toContainText("Waiting for child result")
  await page.setViewportSize({width:375,height:1000})
  await page.screenshot({path:test.info().outputPath("child-source-375.png"),fullPage:true})
  await expect(panel.getByTestId("wait-approval-source")).toHaveCount(0)
  await page.evaluate(()=>window.__waitSources.scenario("missing"));await panel.getByRole("button").click()
  await expect(panel.getByTestId("wait-child-source")).toContainText("Result receipt missing")
  await page.evaluate(()=>window.__waitSources.scenario("settled"));await panel.getByRole("button").click()
  await expect(panel.getByTestId("wait-child-source")).toHaveCount(0)
  await expect(panel).toContainText("No pending approval or bound foreground child call")
  await page.evaluate(()=>window.__waitSources.scenario("background"));await panel.getByRole("button").click()
  await expect(panel.getByTestId("wait-child-source")).toHaveCount(0)
})
test("delayed old server/session/directory responses cannot populate a new owner",async({page})=>{
  for(const change of ["switchSource","switchSession","switchDirectory"] as const){
    await page.evaluate(()=>window.__waitSources.hold("permission"))
    await page.getByRole("button",{name:"Refresh sources"}).click()
    await expect.poll(()=>page.evaluate(()=>window.__waitSources.pending.length)).toBeGreaterThan(0)
    await page.evaluate(change=>{window.__waitSources.hold("");window.__waitSources[change]()},change)
    await expect(page.getByTestId("session-wait-sources")).toHaveAttribute("aria-busy","false")
    const before=await page.getByTestId("wait-approval-source").textContent()
    await page.evaluate(()=>window.__waitSources.release())
    await expect(page.getByTestId("wait-approval-source")).toHaveText(before)
  }
})
test("unmount discards delayed source completion",async({page})=>{
  await page.evaluate(()=>window.__waitSources.hold("permission"));await page.getByRole("button",{name:"Refresh sources"}).click()
  await expect.poll(()=>page.evaluate(()=>window.__waitSources.pending.length)).toBeGreaterThan(0)
  await page.evaluate(()=>{window.__waitSources.unmount();window.__waitSources.release()})
  await expect(page.getByTestId("session-wait-sources")).toHaveCount(0)
})
