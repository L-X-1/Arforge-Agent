/** Read the existing Language API; never change locale preferences. */
export function chooserCopy(locale: string) {
  const value = locale.toLowerCase().replaceAll("_", "-")
  if (value === "zht" || /^zh-(?:hant|tw|hk)(?:-|$)/.test(value)) return traditional
  if (value === "zh" || value.startsWith("zh-")) return messages.zh
  return messages.en
}

export function chooserVariantLabel(value: string | undefined, locale: string, reasoning: boolean, metadata?: unknown) {
  const copy = chooserCopy(locale)
  if (value === undefined) return copy.defaultStrength
  if (!reasoning) return value
  if (value === "none") return chooserReasoningOff(metadata) ? copy.strengthNames.off : value
  if (value === "default") return copy.modelDefault
  return copy.strengthNames[value] ?? value
}
