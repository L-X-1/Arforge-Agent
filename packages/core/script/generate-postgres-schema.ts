import fs from "node:fs/promises"
import path from "node:path"

const root = path.resolve(import.meta.dir, "..")
const migrationRoot = path.join(root, "src", "database", "postgres-migrations")
const output = path.join(root, "src", "database", "postgres-schema.gen.ts")
const migrationDirectories = (await fs.readdir(migrationRoot, { withFileTypes: true }))
  .filter((item) => item.isDirectory())
  .map((item) => item.name)
  .sort()
const migrationIDs: string[] = []
for (const id of migrationDirectories) {
  const pendingMarker = path.join(migrationRoot, id, ".pending-admin")
  const pending = await fs
    .access(pendingMarker)
    .then(() => true)
    .catch(() => false)
  if (!pending) migrationIDs.push(id)
}
if (migrationIDs.length === 0) throw new Error("No PostgreSQL migrations found")

const migrations = await Promise.all(
  migrationIDs.map(async (id) => ({
    id,
    statements: (await Bun.file(path.join(migrationRoot, id, "migration.sql")).text())
      .split("--> statement-breakpoint")
      .map((item) => item.trim())
      .filter(Boolean),
  })),
)

await Bun.write(
  output,
  [
    "// Generated by script/generate-postgres-schema.ts. Do not edit manually.",
    `export const PostgresSchemaMigrations = ${JSON.stringify(migrations, null, 2)} as const`,
    `export const PostgresSchemaVersion = PostgresSchemaMigrations.at(-1)!.id`,
    `export const PostgresSchemaStatements = PostgresSchemaMigrations.flatMap((migration) => migration.statements)`,
    "",
  ].join("\n"),
)

console.log(
  `Generated ${migrations.length} PostgreSQL migrations with ${migrations.reduce(
    (total, migration) => total + migration.statements.length,
    0,
  )} statements`,
)
