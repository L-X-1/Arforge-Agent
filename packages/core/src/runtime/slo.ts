/**
 * Release and operations SLO evaluation.
 *
 * This module evaluates already-redacted aggregate evidence. It deliberately
 * does not accept request bodies, prompts, credentials, or tenant payloads.
 * Missing or malformed evidence is `unknown`, never a passing result.
 */

export const SLO_IDS = [
  "api.availability",
  "api.latency.p95",
  "tenant.isolation",
  "backup.restore",
  "migration.integrity",
] as const

export type SloID = (typeof SLO_IDS)[number]
export type SloStatus = "pass" | "fail" | "unknown"
export type AlertSeverity = "page" | "ticket"
export type AlertStatus = "active" | "inactive"

export const SLO_TARGETS = {
  "api.availability": 0.999,
  "api.latency.p95": 750,
  "tenant.isolation": 1,
  "backup.restore": 1,
  "migration.integrity": 1,
} as const satisfies Record<SloID, number>

export interface ApiSloEvidence {
  readonly totalRequests: number
  readonly goodRequests: number
  readonly p95LatencyMs: number
}

export interface TenantIsolationSloEvidence {
  readonly probeCount: number
  readonly crossScopeViolations: number
  readonly policyBypasses: number
}

export interface BackupRestoreSloEvidence {
  readonly attempts: number
  readonly successful: number
  readonly mismatchCount: number
  readonly temporaryDatabaseCleanup: boolean
}

export interface MigrationIntegritySloEvidence {
  readonly attempts: number
  readonly successful: number
  readonly rowCountMismatch: number
  readonly rlsChecksPassed: boolean
  readonly schemaRevision: string
}

export interface SloWindowEvidence {
  /** Unix epoch milliseconds; no current time is generated by the evaluator. */
  readonly startAt: number
  readonly endAt: number
  readonly api?: ApiSloEvidence
  readonly tenantIsolation?: TenantIsolationSloEvidence
  readonly backupRestore?: BackupRestoreSloEvidence
  readonly migrationIntegrity?: MigrationIntegritySloEvidence
  readonly rateOrBudgetUnexpected?: boolean
}

export interface SloResult {
  readonly id: SloID
  readonly status: SloStatus
  readonly observed: number | null
  readonly target: number
  readonly unit: "ratio" | "milliseconds" | "zero-violations"
  readonly evidenceComplete: boolean
  readonly reason: string
}

export interface SloAlert {
  readonly id:
    | "critical.tenant-isolation"
    | "critical.migration-or-backup"
    | "warning.api-burn"
    | "warning.rate-or-budget"
  readonly severity: AlertSeverity
  readonly status: AlertStatus
  readonly reason: string
}

export interface SloReleaseGate {
  readonly decision: "SHIP" | "DO_NOT_SHIP"
  readonly reasons: ReadonlyArray<string>
}

export interface SloEvaluationReport {
  readonly schema_version: 1
  readonly window: { readonly startAt: number; readonly endAt: number }
  readonly slos: ReadonlyArray<SloResult>
  readonly alerts: ReadonlyArray<SloAlert>
  readonly releaseGate: SloReleaseGate
}

const isFiniteNumber = (value: number): boolean => Number.isFinite(value)
const isNonNegativeInteger = (value: number): boolean => Number.isSafeInteger(value) && value >= 0

const unknownResult = (id: SloID, reason: string): SloResult => ({
  id,
  status: "unknown",
  observed: null,
  target: SLO_TARGETS[id],
  unit: id === "api.latency.p95" ? "milliseconds" : id === "tenant.isolation" ? "zero-violations" : "ratio",
  evidenceComplete: false,
  reason,
})

const ratioResult = (
  id: SloID,
  observed: number,
  target: number,
  reason: string,
  options?: { readonly evidenceComplete?: boolean; readonly status?: SloStatus },
): SloResult => ({
  id,
  status: options?.status ?? (observed >= target ? "pass" : "fail"),
  observed,
  target,
  unit: "ratio",
  evidenceComplete: options?.evidenceComplete ?? true,
  reason,
})

const latencyResult = (observed: number): SloResult => ({
  id: "api.latency.p95",
  status: observed <= SLO_TARGETS["api.latency.p95"] ? "pass" : "fail",
  observed,
  target: SLO_TARGETS["api.latency.p95"],
  unit: "milliseconds",
  evidenceComplete: true,
  reason: observed <= SLO_TARGETS["api.latency.p95"] ? "p95 latency is within target" : "p95 latency exceeds target",
})

function evaluateApi(evidence: ApiSloEvidence | undefined): ReadonlyArray<SloResult> {
  if (!evidence) {
    return [
      unknownResult("api.availability", "API aggregate evidence is missing"),
      unknownResult("api.latency.p95", "API aggregate evidence is missing"),
    ]
  }
  if (
    !isNonNegativeInteger(evidence.totalRequests) ||
    !isNonNegativeInteger(evidence.goodRequests) ||
    evidence.goodRequests > evidence.totalRequests ||
    evidence.totalRequests === 0
  ) {
    return [
      unknownResult("api.availability", "API request counts are missing, empty, or invalid"),
      unknownResult("api.latency.p95", "API request counts are missing, empty, or invalid"),
    ]
  }
  if (!isFiniteNumber(evidence.p95LatencyMs) || evidence.p95LatencyMs < 0) {
    return [
      ratioResult(
        "api.availability",
        evidence.goodRequests / evidence.totalRequests,
        SLO_TARGETS["api.availability"],
        "availability calculated from redacted request counts",
      ),
      unknownResult("api.latency.p95", "p95 latency is missing or invalid"),
    ]
  }
  return [
    ratioResult(
      "api.availability",
      evidence.goodRequests / evidence.totalRequests,
      SLO_TARGETS["api.availability"],
      "availability calculated from redacted request counts",
    ),
    latencyResult(evidence.p95LatencyMs),
  ]
}

function evaluateTenantIsolation(evidence: TenantIsolationSloEvidence | undefined): SloResult {
  if (!evidence) return unknownResult("tenant.isolation", "tenant isolation probe evidence is missing")
  if (
    !isNonNegativeInteger(evidence.probeCount) ||
    !isNonNegativeInteger(evidence.crossScopeViolations) ||
    !isNonNegativeInteger(evidence.policyBypasses) ||
    evidence.probeCount === 0
  ) {
    return unknownResult("tenant.isolation", "tenant isolation probe evidence is missing, empty, or invalid")
  }
  const passed = evidence.crossScopeViolations === 0 && evidence.policyBypasses === 0
  return {
    id: "tenant.isolation",
    status: passed ? "pass" : "fail",
    observed: passed ? 1 : 0,
    target: SLO_TARGETS["tenant.isolation"],
    unit: "zero-violations",
    evidenceComplete: true,
    reason: passed
      ? `all ${evidence.probeCount} isolation probes passed`
      : `isolation violations=${evidence.crossScopeViolations}, policyBypasses=${evidence.policyBypasses}`,
  }
}

function evaluateBackupRestore(evidence: BackupRestoreSloEvidence | undefined): SloResult {
  if (!evidence) return unknownResult("backup.restore", "backup restore drill evidence is missing")
  if (
    !isNonNegativeInteger(evidence.attempts) ||
    !isNonNegativeInteger(evidence.successful) ||
    !isNonNegativeInteger(evidence.mismatchCount) ||
    evidence.attempts === 0 ||
    evidence.successful > evidence.attempts
  ) {
    return unknownResult("backup.restore", "backup restore drill evidence is missing, empty, or invalid")
  }
  const passed =
    evidence.successful === evidence.attempts && evidence.mismatchCount === 0 && evidence.temporaryDatabaseCleanup
  return ratioResult(
    "backup.restore",
    evidence.successful / evidence.attempts,
    SLO_TARGETS["backup.restore"],
    passed
      ? "all restore drills succeeded with zero mismatches and cleanup"
      : `restore successful=${evidence.successful}/${evidence.attempts}, mismatchCount=${evidence.mismatchCount}, cleanup=${evidence.temporaryDatabaseCleanup}`,
    { status: passed ? "pass" : "fail" },
  )
}

function evaluateMigrationIntegrity(evidence: MigrationIntegritySloEvidence | undefined): SloResult {
  if (!evidence) return unknownResult("migration.integrity", "migration validation evidence is missing")
  if (
    !isNonNegativeInteger(evidence.attempts) ||
    !isNonNegativeInteger(evidence.successful) ||
    !isNonNegativeInteger(evidence.rowCountMismatch) ||
    evidence.attempts === 0 ||
    evidence.successful > evidence.attempts ||
    typeof evidence.schemaRevision !== "string" ||
    !evidence.schemaRevision.trim()
  ) {
    return unknownResult("migration.integrity", "migration validation evidence is missing, empty, or invalid")
  }
  const passed =
    evidence.successful === evidence.attempts && evidence.rowCountMismatch === 0 && evidence.rlsChecksPassed
  return ratioResult(
    "migration.integrity",
    evidence.successful / evidence.attempts,
    SLO_TARGETS["migration.integrity"],
    passed
      ? `migration validation passed at schema ${evidence.schemaRevision}`
      : `migration successful=${evidence.successful}/${evidence.attempts}, rowCountMismatch=${evidence.rowCountMismatch}, rlsChecksPassed=${evidence.rlsChecksPassed}`,
    { status: passed ? "pass" : "fail" },
  )
}

const activeAlert = (id: SloAlert["id"], severity: AlertSeverity, reason: string, active: boolean): SloAlert => ({
  id,
  severity,
  status: active ? "active" : "inactive",
  reason,
})

export function evaluateSloWindow(input: SloWindowEvidence): SloEvaluationReport {
  const windowValid = isFiniteNumber(input.startAt) && isFiniteNumber(input.endAt) && input.endAt > input.startAt
  const apiResults = windowValid
    ? evaluateApi(input.api)
    : [
        unknownResult("api.availability", "SLO window is invalid"),
        unknownResult("api.latency.p95", "SLO window is invalid"),
      ]
  const slos: ReadonlyArray<SloResult> = [
    ...apiResults,
    windowValid
      ? evaluateTenantIsolation(input.tenantIsolation)
      : unknownResult("tenant.isolation", "SLO window is invalid"),
    windowValid ? evaluateBackupRestore(input.backupRestore) : unknownResult("backup.restore", "SLO window is invalid"),
    windowValid
      ? evaluateMigrationIntegrity(input.migrationIntegrity)
      : unknownResult("migration.integrity", "SLO window is invalid"),
  ]
  const byID = new Map(slos.map((result) => [result.id, result]))
  const tenant = byID.get("tenant.isolation")!
  const backup = byID.get("backup.restore")!
  const migration = byID.get("migration.integrity")!
  const availability = byID.get("api.availability")!
  const latency = byID.get("api.latency.p95")!

  const alerts: ReadonlyArray<SloAlert> = [
    activeAlert(
      "critical.tenant-isolation",
      "page",
      tenant.status === "pass"
        ? "tenant isolation probes are clean"
        : `tenant isolation status=${tenant.status}: ${tenant.reason}`,
      tenant.status !== "pass",
    ),
    activeAlert(
      "critical.migration-or-backup",
      "page",
      backup.status === "pass" && migration.status === "pass"
        ? "backup restore and migration integrity are clean"
        : `backup=${backup.status}, migration=${migration.status}`,
      backup.status !== "pass" || migration.status !== "pass",
    ),
    activeAlert(
      "warning.api-burn",
      "ticket",
      availability.status === "pass" && latency.status === "pass"
        ? "API availability and latency are within target"
        : `availability=${availability.status}, latency=${latency.status}`,
      availability.status !== "pass" || latency.status !== "pass",
    ),
    activeAlert(
      "warning.rate-or-budget",
      "ticket",
      input.rateOrBudgetUnexpected === true
        ? "rate rejection or settled usage exceeded policy unexpectedly"
        : "no unexpected rate or budget signal",
      input.rateOrBudgetUnexpected === true,
    ),
  ]

  const reasons = [
    ...(windowValid ? [] : ["SLO observation window is invalid"]),
    ...slos
      .filter((result) => result.status !== "pass")
      .map((result) => `${result.id}: ${result.status} — ${result.reason}`),
    ...alerts
      .filter((alert) => alert.status === "active" && alert.severity === "page")
      .map((alert) => `${alert.id}: ${alert.reason}`),
  ]
  return {
    schema_version: 1,
    window: { startAt: input.startAt, endAt: input.endAt },
    slos,
    alerts,
    releaseGate: {
      decision: reasons.length === 0 ? "SHIP" : "DO_NOT_SHIP",
      reasons: [...new Set(reasons)],
    },
  }
}
